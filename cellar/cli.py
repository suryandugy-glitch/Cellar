"""Command-line interface for Cellar."""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import List, Optional

from cellar import __version__
from cellar.checker import (
    InputError,
    check_header,
    format_error_markdown,
    format_markdown,
    format_text,
    load_config,
    read_header,
)

EXIT_OK = 0        # every contract passed
EXIT_FAIL = 1      # at least one contract failed
EXIT_INVALID = 2   # invalid input or configuration; nothing was verified


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="cellar",
        description="Check a CSV export against the columns each integration requires.",
    )
    parser.add_argument("--version", action="version", version=f"cellar {__version__}")
    commands = parser.add_subparsers(dest="command", required=True)

    check = commands.add_parser("check", help="check one CSV file against a contract file")
    check.add_argument("--config", default="cellar.json", help="contract file (default: cellar.json)")
    check.add_argument("--csv", required=True, help="CSV file generated by your exporter")
    check.add_argument(
        "--summary",
        action="store_true",
        help="also write a Markdown report to $GITHUB_STEP_SUMMARY when that variable is set",
    )
    check.add_argument("--format", choices=["text", "json"], default="text", help="output format")

    ui = commands.add_parser("ui", help="open the local web dashboard")
    ui.add_argument("--config", default="cellar.json", help="contract file to edit (default: cellar.json)")
    ui.add_argument("--port", type=int, default=8765)
    ui.add_argument("--no-browser", action="store_true", help="do not open a browser tab")
    return parser


def _write_summary(markdown: str) -> None:
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(markdown + "\n")
    except OSError as exc:
        print(f"WARNING  Could not write the job summary: {exc.strerror or exc}", file=sys.stderr)


def main(argv: Optional[List[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "ui":
        from cellar.server import serve
        return serve(args.config, args.port, not args.no_browser)

    try:
        integrations = load_config(args.config)
        header = read_header(args.csv)
    except InputError as exc:
        print(f"ERROR  {exc}", file=sys.stderr)
        if args.summary:
            _write_summary(format_error_markdown(str(exc)))
        return EXIT_INVALID

    results = check_header(header, integrations)
    if args.format == "json":
        print(json.dumps({"passed": all(r.passed for r in results), "results": [
            {"integration": r.integration, "passed": r.passed, "missing": list(r.missing)} for r in results]}, indent=2))
    else:
        print(format_text(results))
    if args.summary:
        _write_summary(format_markdown(results))
    return EXIT_OK if all(r.passed for r in results) else EXIT_FAIL


if __name__ == "__main__":
    sys.exit(main())
